import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {migrateProject,applyOperation,upperFloorBaseFindings} from '../src/lib/architecture.ts';
let p=migrateProject(JSON.parse(readFileSync(new URL('../public/demo-fixtures/sukoon-studio-demo.archmorph.json',import.meta.url),'utf8')).project);
p=applyOperation(p,{type:'create_floor',name:'Test upper floor'},'agent').project;
const floor=p.floors.find(f=>f.name==='Test upper floor')!;
const before=p.version;
assert.throws(()=>applyOperation(p,{type:'create_room',floorId:floor.id,name:'Overhang',roomType:'Bedroom',x:5,y:12,width:20,length:15},'agent'),/beyond the modeled footprint below/);
assert.equal(p.version,before,'rejected room must not mutate the project');
const created=applyOperation(p,{type:'create_room',floorId:floor.id,name:'Aligned',roomType:'Bedroom',x:6,y:14,width:14,length:14},'agent');p=created.project;
const room=created.result.room as {id:string};
assert.equal(upperFloorBaseFindings(p,floor.id).some(f=>f.elementId===room.id),false);
assert.throws(()=>applyOperation(p,{type:'move_room',roomId:room.id,x:5,y:5},'agent'),/beyond the modeled footprint below/);
assert.equal(p.rooms.find(r=>r.id===room.id)?.x,6,'rejected move must preserve the room');
console.log('PASS: agent upper-floor placement and move preserve the modeled lower footprint');
let empty = applyOperation(p,{type:'create_floor',name:'Empty roof'},'agent').project;
const emptyId=empty.floors.find(f=>f.name==='Empty roof')!.id;
empty = applyOperation(empty,{type:'create_floor',name:'Another level'},'agent').project;
const topId=empty.floors.find(f=>f.name==='Another level')!.id;
assert.throws(()=>applyOperation(empty,{type:'create_room',floorId:topId,name:'Unknown base',roomType:'Bedroom',x:6,y:14,width:10,length:10},'agent'),/no modeled footprint/);
assert.equal(empty.rooms.some(r=>r.floorId===emptyId),false);
